package com.example.simple.manymanager.data.local

import android.content.Context
import android.database.sqlite.SQLiteConstraintException
import androidx.room.Room
import androidx.room.testing.MigrationTestHelper
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import java.time.LocalDate
import java.util.UUID
import kotlinx.coroutines.async
import kotlinx.coroutines.awaitAll
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.*
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class ManyManagerDatabaseTest {
    @get:Rule
    val schemaHelper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(), ManyManagerDatabase::class.java
    )

    private val context = ApplicationProvider.getApplicationContext<Context>()
    private lateinit var database: ManyManagerDatabase
    private val testFiles = mutableListOf<String>()
    private val owner = ManyManagerDao.LOCAL_CALCULATOR_ID
    private val period = LocalDate.of(2026, 11, 10).toEpochDay()
    private val date = LocalDate.of(2026, 12, 9).toEpochDay()
    private val source get() = BudgetSourceEntity(owner, "source-a", "Cash")
    private val category get() = CategoryEntity(owner, "category-a", "Food")

    @Before fun open() {
        database = Room.inMemoryDatabaseBuilder(context, ManyManagerDatabase::class.java).build()
    }

    @After fun close() {
        database.close()
        // Only names generated by this test are removed, never the application's database.
        testFiles.forEach { context.deleteDatabase(it) }
    }

    @Test fun freshDatabaseInitializesOnceWithoutSeedingBusinessData() = runBlocking {
        val first = database.dao().initializeLocalCalculator()
        assertEquals(CalculatorEntity(owner, 10, "ILS"), first)
        assertEquals(first, database.dao().initializeLocalCalculator())
        assertEquals(1L, count("calculators"))
        listOf("categories", "budget_sources", "period_budgets", "expenses").forEach {
            assertEquals(0L, count(it))
        }
    }

    @Test fun repeatedConcurrentInitializationIsSafe() = runBlocking {
        coroutineScope {
            (1..12).map { async { database.dao().initializeLocalCalculator() } }.awaitAll()
        }
        assertEquals(1L, count("calculators"))
    }

    @Test fun initializationDoesNotOverwriteSettings() = runBlocking {
        database.dao().initializeLocalCalculator()
        database.openHelper.writableDatabase.execSQL(
            "UPDATE calculators SET periodStartDay = 15, currencyCode = 'EUR' WHERE id = ?",
            arrayOf(owner)
        )
        assertEquals(CalculatorEntity(owner, 15, "EUR"), database.dao().initializeLocalCalculator())
    }

    @Test fun recordsSurviveClosingAndReopeningFileDatabase() = runBlocking {
        val name = newTestFile()
        database.close()
        database = Room.databaseBuilder(context, ManyManagerDatabase::class.java, name).addMigrations(ManyManagerDatabase.MIGRATION_1_2).build()
        seedRelationships()
        val allocation = PeriodBudgetEntity(owner, period, 12345L)
        val categorized = expense("categorized")
        val uncategorized = expense("uncategorized", categoryId = null)
        database.dao().insertBudget(allocation)
        database.dao().insertExpense(categorized)
        database.dao().insertExpense(uncategorized)
        database.close()

        database = Room.databaseBuilder(context, ManyManagerDatabase::class.java, name)
            .addMigrations(ManyManagerDatabase.MIGRATION_1_2).build()
        assertEquals(CalculatorEntity(owner), database.dao().initializeLocalCalculator())
        assertEquals(1L, count("calculators"))
        assertEquals(allocation, database.dao().periodBudget(owner, period))
        assertEquals(categorized, database.dao().expense(owner, categorized.id))
        assertEquals(uncategorized, database.dao().expense(owner, uncategorized.id))
        assertEquals(1L, count("categories"))
        assertEquals(1L, count("budget_sources"))
    }

    @Test fun duplicatePeriodBudgetAbortsAndPreservesOriginal() = runBlocking {
        seedRelationships()
        val original = PeriodBudgetEntity(owner, period, 100L)
        database.dao().insertBudget(original)
        expectConstraint { database.dao().insertBudget(original.copy(amountMinor = 999L)) }
        assertEquals(original, database.dao().periodBudget(owner, period))
        database.dao().insertBudget(original.copy(
            periodStartEpochDay = LocalDate.of(2026, 12, 10).toEpochDay()
        ))
        assertEquals(2L, count("period_budgets"))
    }

    @Test fun validRelationshipsAndNullCategoryAreAccepted() = runBlocking {
        seedRelationships()
        val categorized = expense("one")
        val uncategorized = expense("two", categoryId = null)
        database.dao().insertExpense(categorized)
        database.dao().insertExpense(uncategorized)
        assertEquals(categorized, database.dao().expense(owner, "one"))
        assertEquals(uncategorized, database.dao().expense(owner, "two"))
        // Neither source existence nor spending requires a budget allocation.
        assertEquals(0L, count("period_budgets"))
    }

    @Test fun unknownCategoryAndSourceAreRejected() = runBlocking {
        seedRelationships()
        expectConstraint {
            database.dao().insertExpense(expense("bad-category", categoryId = "missing"))
        }
        expectConstraint {
            database.dao().insertExpense(expense("bad-source", sourceId = "missing"))
        }
        expectConstraint {
            database.dao().insertExpense(expense("uncategorized-bad-source",
                categoryId = null, sourceId = "missing"))
        }
        expectConstraint {
            database.dao().insertBudget(PeriodBudgetEntity("missing", period, 100L))
        }
        assertEquals(0L, count("expenses"))
    }

    @Test fun crossCalculatorRelationshipsAreRejected() = runBlocking {
        seedRelationships()
        database.openHelper.writableDatabase.execSQL(
            "INSERT INTO calculators VALUES ('other', 10, 'ILS')"
        )
        database.dao().insertCategory(CategoryEntity("other", "other-category", "Food"))
        database.dao().insertSource(BudgetSourceEntity("other", "other-source", "Cash"))
        expectConstraint {
            database.dao().insertExpense(expense("cross-category", categoryId = "other-category"))
        }
        expectConstraint {
            database.dao().insertExpense(expense("cross-source", sourceId = "other-source"))
        }
        val validOther = ExpenseEntity("other", "valid-other", 50L, date,
            "other-category", "other-source")
        database.dao().insertExpense(validOther)
        assertEquals(validOther, database.dao().expense("other", "valid-other"))
        assertNull(database.dao().expense(owner, "valid-other"))
    }

    @Test fun sourceCannotBeNullAndChildrenRequireCalculator() = runBlocking {
        seedRelationships()
        expectConstraint {
            database.openHelper.writableDatabase.execSQL(
                """INSERT INTO expenses
                    (calculatorId, id, amountMinor, dateEpochDay, categoryId, sourceId, note)
                    VALUES (?, 'null-source', 1, ?, NULL, NULL, NULL)""",
                arrayOf<Any?>(owner, date)
            )
        }
        expectConstraint {
            database.dao().insertCategory(CategoryEntity("missing", "cat", "Food"))
        }
        expectConstraint {
            database.dao().insertSource(BudgetSourceEntity("missing", "src", "Cash"))
        }
    }

    @Test fun referencedParentsCannotBeDeletedOrCascadeAwayHistory() = runBlocking {
        seedRelationships()
        val original = expense("history")
        database.dao().insertExpense(original)
        expectConstraint {
            database.openHelper.writableDatabase.execSQL(
                "DELETE FROM categories WHERE calculatorId = ? AND id = ?",
                arrayOf(owner, category.id)
            )
        }
        expectConstraint {
            database.openHelper.writableDatabase.execSQL(
                "DELETE FROM budget_sources WHERE calculatorId = ? AND id = ?",
                arrayOf(owner, source.id)
            )
        }
        expectConstraint {
            database.openHelper.writableDatabase.execSQL(
                "DELETE FROM calculators WHERE id = ?", arrayOf(owner)
            )
        }
        assertEquals(original, database.dao().expense(owner, original.id))
        assertEquals(1L, count("categories"))
        assertEquals(1L, count("budget_sources"))
        assertEquals(1L, count("calculators"))
    }

    @Test fun schemaOneAllowsDuplicateNamesAndLeavesAmountValidationToRepository() = runBlocking {
        seedRelationships()
        database.dao().insertCategory(category.copy(id = "category-b"))
        database.dao().insertSource(source.copy(id = "source-b"))
        listOf(0L, -100L, Long.MAX_VALUE).forEachIndexed { index, amount ->
            val record = expense("amount-$index").copy(amountMinor = amount)
            database.dao().insertExpense(record)
            assertEquals(record, database.dao().expense(owner, record.id))
        }
        assertEquals(2L, count("categories"))
        assertEquals(2L, count("budget_sources"))
    }

    @Test fun exportedVersionOneSchemaOpensAndValidatesAgainstEntities() = runBlocking {
        val name = newTestFile()
        // Populate the exported schema before Room opens it: validation must preserve old facts.
        schemaHelper.createDatabase(name, 1).use { saved ->
            saved.execSQL("INSERT INTO calculators VALUES (?, 15, 'EUR')", arrayOf(owner))
            saved.execSQL("INSERT INTO categories VALUES (?, ?, ?)", arrayOf(owner, category.id, category.name))
            saved.execSQL("INSERT INTO budget_sources VALUES (?, ?, ?)", arrayOf(owner, source.id, source.name))
            saved.execSQL("INSERT INTO budget_allocations VALUES (?, ?, ?, 12345)", arrayOf<Any>(owner, source.id, period))
            saved.execSQL("INSERT INTO expenses VALUES (?, 'schema', 12345, ?, ?, ?, 'Test note')",
                arrayOf<Any>(owner, date, category.id, source.id))
            saved.execSQL("INSERT INTO expenses VALUES (?, 'schema-null', 12345, ?, NULL, ?, 'Test note')",
                arrayOf<Any>(owner, date, source.id))
        }
        database.close()
        database = Room.databaseBuilder(context, ManyManagerDatabase::class.java, name)
            .addMigrations(ManyManagerDatabase.MIGRATION_1_2).build()
        assertEquals(CalculatorEntity(owner, 15, "EUR"), database.dao().initializeLocalCalculator())
        assertEquals(listOf(category), database.dao().categories(owner))
        assertEquals(listOf(source), database.dao().sources(owner))
        assertEquals(PeriodBudgetEntity(owner, period, 12345),
            database.dao().periodBudget(owner, period))
        assertEquals(expense("schema"), database.dao().expense(owner, "schema"))
        assertEquals(expense("schema-null", categoryId = null), database.dao().expense(owner, "schema-null"))
        assertEquals(2L, count("expenses"))
    }

    private suspend fun seedRelationships() {
        database.dao().initializeLocalCalculator()
        database.dao().insertSource(source)
        database.dao().insertCategory(category)
    }

    private fun expense(
        id: String, categoryId: String? = category.id, sourceId: String = source.id
    ) = ExpenseEntity(owner, id, 12345L, date, categoryId, sourceId, "Test note")

    private fun count(table: String): Long =
        database.openHelper.readableDatabase.query("SELECT COUNT(*) FROM $table").use {
            assertTrue(it.moveToFirst())
            it.getLong(0)
        }

    private suspend fun expectConstraint(block: suspend () -> Unit) {
        try {
            block()
            fail("Expected SQLite constraint rejection")
        } catch (_: SQLiteConstraintException) {
            // A real database constraint failed, not application validation or a fake.
        }
    }

    private fun newTestFile(): String =
        "many-manager-test-${UUID.randomUUID()}.db".also { testFiles.add(it) }
}
